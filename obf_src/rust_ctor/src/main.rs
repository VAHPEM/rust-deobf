#![allow(static_mut_refs)]
// Benign Rust fixture (VALIDATION, obf_src): two strings sit XOR-encrypted in a mutable static
// (.data) and ONE global constructor from the `ctor` crate decrypts them in place before main.
// Nothing decodes at the use site, so an analyzer that emulates functions in isolation sees only
// ciphertext; the loader's constructors must run first. Rust counterpart of hikari_ctor.c.
use ctor::ctor;

const K: u8 = 0x5c;
static mut S0: [u8; 34] = [0x3f,0x3d,0x32,0x3d,0x2e,0x25,0x66,0x66,0x2e,0x29,0x2f,0x28,0x3f,0x28,0x33,0x2e,0x66,0x66,0x2f,0x28,0x2e,0x35,0x32,0x3b,0x71,0x33,0x32,0x39,0x66,0x66,0x6b,0x3a,0x6f,0x3d];
static mut S1: [u8; 34] = [0x3f,0x3d,0x32,0x3d,0x2e,0x25,0x66,0x66,0x2e,0x29,0x2f,0x28,0x3f,0x28,0x33,0x2e,0x66,0x66,0x2f,0x28,0x2e,0x35,0x32,0x3b,0x71,0x28,0x2b,0x33,0x66,0x66,0x65,0x38,0x6e,0x6d];

#[ctor]
fn rustctor_decrypt() {
    unsafe {
        let mut i = 0; while i < S0.len() { S0[i] ^= K; i += 1; }
        let mut j = 0; while j < S1.len() { S1[j] ^= K; j += 1; }
    }
}

fn main() {
    unsafe {
        println!("{}", std::str::from_utf8(&S0).unwrap());
        println!("{}", std::str::from_utf8(&S1).unwrap());
    }
}
